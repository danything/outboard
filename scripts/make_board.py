def keepouts(bd: Board):
    """自動配線に通らせたくない所。"""
    # うらの GND を切らせたくない所 (USB のデータ線の下、降圧と昇圧の下): うらの配線を禁止
    bd.keepout([B], rect(69.0, 10.3, 78.8, 14.8), name="usb-gnd-1")
    bd.keepout([B], rect(80.0, 10.9, 82.5, 15.7), name="usb-gnd-2")
    bd.keepout([B], rect(35.0, 1.0, 55.5, 11.0), name="buck-gnd")
    bd.keepout([B], rect(25.0, 32.4, 38.5, 43.0), name="boost-gnd")
    # USB-C の殻の下: ビアを置かせない。パッドのすぐ内側のうらの線も禁止 (CC の線はパッドから左へ出て、殻の外でビアに降りる)
    for name, y in (("J1", J1Y), ("J2", J2Y)):
        bd.keepout([F, B], rect(82.65, y - 3.7, 89.9, y + 3.7), tracks=False, vias=True, name=name + "-shell-no-via")
        bd.keepout([B], rect(82.65, y - 3.7, 84.6, y + 3.7), name=name + "-shell-no-bottom-track")
    # D1・D2 の胴体の下: おもての線を禁止 (熱くなる部品の下を信号や +5V が通らないように)
    bd.keepout([F], rect(59.75, 19.6, 62.25, 21.4), name="D1-body")
    bd.keepout([F], rect(59.75, J2Y - 0.9, 62.25, J2Y + 0.9), name="D2-body")


def main():
    bd = build()
    route(bd)
    keepouts(bd)
    os.makedirs(os.path.join(ROOT, "build"), exist_ok=True)
    out = os.path.join(ROOT, "build", "pre_route.kicad_pcb")
    bd.save(out)
    for ext in ("kicad_pro", "kicad_dru"):
        shutil.copyfile(os.path.join(ROOT, "pcie-tuner-board." + ext), os.path.join(ROOT, "build", "pre_route." + ext))
    for f in ("fp-lib-table", "sym-lib-table"):
        shutil.copyfile(os.path.join(ROOT, f), os.path.join(ROOT, "build", f))
    print("saved", out, "footprints", len(bd.fps))
    return bd


if __name__ == "__main__":
    main()
