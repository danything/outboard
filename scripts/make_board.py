def outline(bd: Board):
    E = pcbnew.Edge_Cuts
    kx1, kx2, kr = KEY_X - KEY_W / 2, KEY_X + KEY_W / 2, KEY_W / 2
    bd.line(E, STEP_X + R, 0, kx1, 0, 0.1)
    bd.line(E, kx1, 0, kx1, KEY_D - kr, 0.1)                 # キーの切り欠き
    bd.arc(E, KEY_X, KEY_D - kr, kr, 180, 0, 0.1)
    bd.line(E, kx2, KEY_D - kr, kx2, 0, 0.1)
    bd.line(E, kx2, 0, W - R, 0, 0.1)
    bd.arc(E, W - R, R, R, 270, 360, 0.1)
    bd.line(E, W, R, W, H - R, 0.1)
    bd.arc(E, W - R, H - R, R, 0, 90, 0.1)
    bd.line(E, W - R, H, R, H, 0.1)
    bd.arc(E, R, H - R, R, 90, 180, 0.1)
    bd.line(E, 0, H - R, 0, STEP_Y, 0.1)
    bd.line(E, 0, STEP_Y, STEP_X, STEP_Y, 0.1)               # 段
    bd.line(E, STEP_X, STEP_Y, STEP_X, R, 0.1)
    bd.arc(E, STEP_X + R, R, R, 180, 270, 0.1)


# 取り付け穴 (M3、穴 3.2mm)。H3 は後ろの遠い角が USB-C でふさがるので、2 つの USB-C の間
HOLES = (("H1", STEP_X + 3.5, 3.5), ("H2", W - 3.5, 3.5), ("H3", 3.5, (J1Y + J2Y) / 2), ("H4", W - 3.5, H - 3.5))
LEDS = (("LED3", 91.5), ("LED5", 63.8))     # 下の長い辺 (カードと反対の辺) の LED の x
LED_Y = H - 1.0


def plen(pts):
    return sum(math.hypot(b[0] - a[0], b[1] - a[1]) for a, b in zip(pts, pts[1:]))


def build() -> Board:
    bd = Board()
    outline(bd)
    for ref, x, y in HOLES:
        bd.place(ref, x, y)

    # ---- 端子 ---------------------------------------------------------------
    bd.place("J3", SLOT[0], SLOT[1], 0)       # 口は上 (基板の外)。1 番ピンが左。B 列がおもて、A 列がうら
    bd.place("J1", JX, J1Y, 270)              # 口が左を向く
    bd.place("J2", JX, J2Y, 270)
    bd.place("J4", J4X, J4Y, 180)             # プラグは上へ寝る。1 番ピンが右、奇数の列 (下の段) が上

    # ---- ① USB-C のまわり -----------------------------------------------------
    with bd.frame(**USB1):
        bd.place("U5", 74.5, 12.5, 180)       # 1 (IO1)・3 (IO2) が J4 の側
        bd.place("R3", 86.2, 20.6, pin1="W")
        bd.place("C2", 86.2, 22.5, pin1="W")
    bd.place("U1", U1X, U1Y, 90)              # 6・7 (CC) が左、1 (VHV) が右下
    bd.place("R1", U1X - 0.6, U1Y + 3.76, pin1="W")
    bd.place("C1", U1X + 3.0, U1Y + 3.76, pin1="E")
    bd.place("R22", 28.4, 26.3, pin1="N")     # CC2 の線の上にパッド 1
    bd.place("R21", 33.0, 18.4, pin1="W")     # CC1 の線の先 (J4 の樹脂の右)
    bd.place("JP3", 33.0, 21.0, pin1="E")     # 左が USBH_VBUS (J4 の 1 番)、右が +5V
    bd.place("R8", 36.2, 16.3, pin1="N")      # U3 の EN の分圧の上の抵抗 (D1 のアノードの面のすぐ下)
    # ブリーダ (1kΩ 0805 を 2 直列 x 2 並列)。アノードの面の左の端。J4 のプラグの下には入らない
    bd.place("R28", 11.2, 9.6, pin1="W")
    bd.place("R29", 15.5, 9.6, pin1="W")
    bd.place("R39", 11.2, 11.9, pin1="W")
    bd.place("R40", 15.5, 11.9, pin1="W")
    bd.place("D1", 36.6, D1Y, pin1="W")       # アノードが左 (VBUS1 の面)、カソード (帯) が右 (VIN の帯)

    # ---- ② USB-C のまわり (rev C の形のまま) ----------------------------------
    bd.place("U2", 13.5, J2Y + 0.75, 90)
    bd.place("R4", 12.9, J2Y + 4.35, pin1="W")
    bd.place("C3", 18.5, J2Y + 4.1, pin1="S")
    bd.place("R30", 23.0, J2Y - 1.5, pin1="W")
    bd.place("R31", 27.4, J2Y - 1.5, pin1="W")
    bd.place("R41", 23.0, J2Y + 0.8, pin1="W")
    bd.place("R42", 27.4, J2Y + 0.8, pin1="W")
    bd.place("D2", 36.6, D2Y, pin1="W")
    # 過電圧の遮断 (VIN が約 13V を超えたら Q2 のゲートを GND に引く)。帯の左、D2 の下
    bd.place("D7", 35.4, 36.0, pin1="E")      # カソード (パッド 1、帯) が右 = VIN の帯の側
    bd.place("R35", 31.6, 36.0, pin1="E")
    bd.place("R36", 31.6, 37.8, pin1="W")
    bd.place("Q4", 34.8, 38.9, 180)           # 左上が 1 B、左下が 2 E、右が 3 C

    # ---- VIN の帯の中 ----------------------------------------------------------
    bd.place("C4", 39.3, 36.6, pin1="N")
    bd.place("C5", 41.6, 36.6, pin1="N")
    bd.place("TP1", 44.2, 36.6)

    # ---- 3.3V の降圧 (rev B の形を 180 度回したもの) ---------------------------
    with bd.frame(**BUCK):
        bd.place("U3", 47.0, 9.0, 0)
        bd.place("C10", 49.15, 8.5, pin1="S")
        bd.place("C8", 51.1, 8.6, pin1="S")
        bd.place("C9", 53.5, 8.6, pin1="S")
        bd.place("C11", 44.6, 8.25, pin1="S")
        bd.place("L1", 39.3, 5.5, pin1="E")
        bd.place("C12", 44.8, 11.2, pin1="E")
        bd.place("R7", 45.6, 12.9, pin1="E")
        bd.place("R6", 49.2, 12.9, pin1="E")
        bd.place("C13", 33.3, 5.2, pin1="S")
        bd.place("C14", 30.9, 5.2, pin1="S")
    bd.place("JP5", U3X + 19.0, U3Y + 2.8, pin1="W")     # 閉じたはんだジャンパー (3.3V の 3A が通る)
    bd.place("JP1", U3X + 19.0, U3Y - 0.5, pin1="W")     # JP5 に並列のヘッダ (電流を測るとき用。載せない)
    bd.place("R9", 54.4, 11.9, pin1="S")      # EN の分圧の下
    bd.place("C15", 56.9, 11.9, pin1="S")     # EN のコンデンサ
    bd.place("C27", 59.6, 11.0, pin1="N")     # 3.3V の出口のコンデンサ (幹のすぐ下・すぐ上)
    bd.place("C28", 61.5, 6.1, pin1="W")
    bd.place("TP2", 78.0, YT)
    bd.place("JP4", SLOT[0] - 0.5, 6.9, pin1="S")        # B10 (+3V3AUX) のすぐ下。下のパッドは幹の上

    # ---- 5V の LDO (VIN の幹のすぐ下) ------------------------------------------
    bd.place("U6", 51.9, 19.9, 270)           # 上が 2 VIN (タブ)、左下が 1 GND、右下が 3 VOUT
    bd.place("C6", 55.6, 18.2, pin1="N")
    bd.place("C7", 56.6, 21.7, pin1="W")

    # ---- 12V: スロットのそば・戻りの列 ------------------------------------------
    bd.place("C29", 48.8, 11.4, pin1="N")
    bd.place("C30", 46.75, 10.9, pin1="N")
    bd.place("TP3", X12, 22.6)
    bd.place("R18", 46.75, 18.5, pin1="N")
    bd.place("R32", 48.9, 26.65, pin1="N")     # +12V を読む分圧の上の抵抗
    bd.place("JP6", 52.9, ROW, pin1="E")      # 右が +12V_F、左が +12V
    bd.place("JP2", 58.5, ROW, pin1="E")      # JP6 に並列のヘッダ (載せない)
    bd.place("F1", 64.0, ROW, pin1="E")

    # ---- 12V の昇圧 (rev B の形を 180 度回したもの) と出力スイッチ -------------
    with bd.frame(**BOOST):
        bd.place("U4", 33.5, 40.65, 180)
        bd.place("L2", 30.1, 33.95, pin1="E")
        bd.place("D4", 27.9, 39.15, pin1="W")
        bd.place("C16", 37.55, 40.05, pin1="N")
        bd.place("C17", 39.7, 40.05, pin1="N")
        bd.place("C18", 28.5, 41.9, pin1="W")
        bd.place("C19", 24.2, 41.9, pin1="E")
        bd.place("R12", 33.4, 43.87, pin1="W")
        bd.place("R11", 30.2, 43.87, pin1="W")
    bd.place("R13", U4X - 4.0, 28.6, pin1="E")
    bd.place("Q1", 91.5, 21.8, 0)             # 左が 3 D、右上が 2 S、右下が 1 G
    bd.place("R14", 94.3, 21.6, pin1="S")
    bd.place("C20", 96.1, 21.55, pin1="S")
    bd.place("C32", 90.9, 24.42, pin1="E")
    bd.place("R15", 94.3, 25.0, pin1="N")
    bd.place("Q3", 97.0, 25.3, 0)             # 左が 3 D、右上が 2 S、右下が 1 G
    bd.place("Q2", 97.0, 29.2, 0)

    # ---- マイコン -----------------------------------------------------------
    with bd.frame(**MCU):
        bd.place("U7", 46.5, 29.0, 0)         # 下の列が左から 1..10、上の列が左から 20..11
        bd.place("C21", 48.1, 34.5, pin1="E")
        bd.place("C22", 51.3, 34.5, pin1="W")
    # ADC の入力のコンデンサはマイコンの左に縦に並べる (右が信号、左が GND)
    for i, ref in enumerate(("C25", "C26", "C23", "C24", "C33")):
        bd.place(ref, U7X - 5.55, 30.4 + 1.9 * i, pin1="E")
    bd.place("R25", 47.0, 32.3, pin1="N")     # VBUS1 を読む分圧 (帯のすぐ右に縦に)
    bd.place("R26", 47.0, 35.6, pin1="N")
    bd.place("R23", 49.6, 38.7, pin1="S")     # VIN を読む分圧 (上の抵抗は下の帯から)
    bd.place("R24", 51.4, 38.3, pin1="S")
    bd.place("R27", 53.3, 31.6, pin1="N")     # PERST# の遅延
    bd.place("D6", 55.3, 31.6, pin1="N")      # カソード (パッド 1、帯) が上 = +3V3
    bd.place("C31", 54.3, 35.6, pin1="E")
    bd.place("R37", 54.6, 37.7, pin1="W")
    bd.place("R38", 50.9, 31.5, pin1="S")
    bd.place("R34", U7X + 5.4, 28.6, pin1="W")
    bd.place("R16", U7X + 8.8, 28.6, pin1="W")
    bd.place("D5", U7X + 4.9, 32.0, pin1="N")      # カソード (パッド 1、帯) が上 = +5V
    bd.place("R19", U7X + 7.0, 31.0, pin1="N")
    bd.place("JP7", U7X + 9.2, 31.2, pin1="S")     # 12V の強制オン (はんだでつなぐ)
    bd.place("TP4", U7X + 5.7, 36.2)
    bd.place("J5", U7X + 9.2, 36.6, pin1="N")
    bd.place("R33", U7X - 2.0, 39.0, pin1="W")
    bd.place("TP5", 86.5, 4.5)
    # LED (下の長い辺。辺から 1mm 以内)。直列の抵抗はすぐ左
    bd.place("R10", W - 4.5, 35.6, pin1="E")         # LED3 (3.3V) の直列抵抗。+3V3 は Q3 のゲートの線から
    bd.place("R20", 60.5, LED_Y + 0.1, pin1="W")
    for ref, x in LEDS:
        bd.place(ref, x, LED_Y, pin1="W")
    return bd


def route(bd: Board):
    """電源・USB・CC・帯をくぐる線を手で引く。残りの細い信号は freerouting に任せる。"""
    P = bd.P
    T = bd.track

    # ======== USB のデータ線 (J1 -> U5 は rev B の形のまま。その先は J4 の上の列へ) ======
    with bd.frame(**USB1):
        dp6, dn7, dp_a6, dn_b7 = P("J1", "B6"), P("J1", "A7"), P("J1", "A6"), P("J1", "B7")
        io1, io2 = P("U5", "1"), P("U5", "3")
        w0, w1 = 0.2, 0.5
        yp, yn = io1[1] - 0.85, io2[1] + 0.85            # U5 の使わないパッド (IO4・IO3) の外を回る
        dp_a = [dp6, (82.5, dp6[1]), (82.0, dp6[1] - 0.5), (77.9, dp6[1] - 0.5), (76.35, yp)]
        dp_b = [(76.35, yp), (74.2, yp), (io1[0] + 0.2, io1[1]), io1]
        dn_a = [dn7, (81.9, dn7[1]), (81.4, dn7[1] - 0.5), (77.9, dn7[1] - 0.5), (76.35, yn)]
        dn_b = [(76.35, yn), (74.2, yn), (io2[0] + 0.2, io2[1]), io2]
        T("USB_DP", w0, dp_a)
        T("USB_DP", w1, dp_b)
        T("USB_DN", w0, dn_a)
        T("USB_DN", w1, dn_b)
        len_p, len_n = plen(dp_a) + plen(dp_b), plen(dn_a) + plen(dn_b)
        # 裏返しに挿したとき用の D+ (A6): ビアで裏へ回り、D- の下をくぐって D+ に合流
        va, vb = (79.4, dp_a6[1]), (79.4, 11.5)
        T("USB_DP", w0, [dp_a6, va])
        bd.via("USB_DP", *va)
        T("USB_DP", w0, [va, vb], layer=B)
        bd.via("USB_DP", *vb)
        T("USB_DP", w0, [vb, (79.4, dp6[1] - 0.5)])
