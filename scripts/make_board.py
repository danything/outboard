"""基板を組み立てる (1 段目): 外形・部品の配置・電源と USB と長い制御線の手配線・GND のビア・銅の面。rev D。

出力: build/pre_route.kicad_pcb (自動配線の前の基板)
このあと scripts/export_dsn.py・scripts/route.sh (freerouting)・scripts/finish_board.py (取り込み・ベタ・シルク) を実行する。

座標は基板の左上の角を (0, 0) とした mm。x は右、y は下。基板は 100 x 44mm の 1 枚。
- 左の辺 (x = 0) がカードのブラケットの側で、USB-C が 2 つ並ぶ。USB-C の口の面は x = -0.99 = ブラケットの外の面。
- 上の長い辺 (y = 0) がカードの側。PCIe のスロット J3 が辺をまたいで付き (straddle mount)、カードは基板と同じ平面で
  y < 0 の側に来る。おもて = カードの部品面 (B) の側。J3 の B 列がおもて、A 列がうら。
- ブラケットの板が通る所 (y < 10) は、左の辺を 1.5mm 引っ込めてある。
- J4 (内部 USB、横向き) はプラグが上 (カードの辺の側) へ寝る。プラグの下は D1 のアノードの面 (銅だけ)。

置き方の筋 (どのネットも、おもてでは交差させない):
  左: USB-C 2 個と PD の IC・J4。その右に VIN の帯 (D1・D2 のカソード)。
  帯の右の上の段: 3.3V の降圧 (入力が左、出力が右) と、その上を左へ戻る 3.3V の幹。
  下の段: マイコン (帯のすぐ右) と 12V の昇圧 (右)。12V は右上の Q1 から「戻りの列」(y = 25.3) を左へ戻り、
  帯の右を上がって、VIN の幹の下だけうらでくぐり、スロットのうらのパッド (A2・A3) に入る。
  左右をまたぐ信号は、VIN の帯をうらでくぐる (本数と長さは check_board.py が記録する)。

降圧・昇圧・USB の線・マイコンの電源は rev B で確かめた形のまま、回して置き直している (board_lib.py の「枠」)。

使い方: "C:\\Program Files\\KiCad\\10.0\\bin\\python.exe" scripts/make_board.py
"""
