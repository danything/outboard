"""基板を組み立てる (1 段目): 外形・部品の配置・電源と USB と長い制御線の手配線・GND のビア・銅の面。rev B。

出力: build/pre_route.kicad_pcb (自動配線の前の基板)
このあと scripts/export_dsn.py・scripts/route.sh (freerouting)・scripts/finish_board.py (取り込み・ベタ・シルク) を実行する。

座標は基板の左上の角を (0, 0) とした mm。x は右、y は下。基板は 90 x 48mm (rev B の途中で下へ 3mm 広げた)。
左の辺 (x = 0) がカードのブラケットの側、右の辺 (x = 90) に USB-C が 2 つ。

使い方: "C:\\Program Files\\KiCad\\10.0\\bin\\python.exe" scripts/make_board.py
"""
from __future__ import annotations

import os
import shutil
import sys

import pcbnew

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from board_lib import B, F, ROOT, Board, rect  # noqa: E402

W, H, R = 90.0, 48.0, 3.0

# --- 配置の基準になる座標 ---------------------------------------------------
J1Y, J2Y = 13.5, 32.9          # USB-C の中心の y
JX = 85.92                      # USB-C の原点の x。基板の端 (x=90) は、後ろの殻の穴から 5.79mm (データシートの図)
BUS = 57.5                      # VIN の幹 (縦) の x
U3X, U3Y = 47.0, 9.0            # 降圧 IC
U4X, U4Y = 33.5, 40.65          # 昇圧 IC
SLOT = (17.6, 22.5)             # PCIe スロット
P5X = 55.9                      # +5V の縦の線 (VIN の幹のすぐ左)
LANE_SW, LANE_EN = 41.2, 40.8   # SW12_ON と EN_12V の縦の線 (マイコンの左)
YEDGE = 44.52                   # 下の辺に沿って走る SW12_ON の y


def build() -> Board:
    bd = Board()

    # ---- 外形 (角の丸い四角) と取り付け穴 -----------------------------------
    E = pcbnew.Edge_Cuts
    bd.line(E, R, 0, W - R, 0, 0.1)
    bd.line(E, W, R, W, H - R, 0.1)
    bd.line(E, W - R, H, R, H, 0.1)
    bd.line(E, 0, H - R, 0, R, 0.1)
    bd.arc(E, R, R, R, 180, 270, 0.1)
    bd.arc(E, W - R, R, R, 270, 360, 0.1)
    bd.arc(E, W - R, H - R, R, 0, 90, 0.1)
    bd.arc(E, R, H - R, R, 90, 180, 0.1)
    for ref, x, y in (("H1", 3.5, 3.5), ("H2", W - 3.5, 3.5), ("H3", 3.5, H - 3.5), ("H4", W - 3.5, H - 3.5)):
        bd.place(ref, x, y)

    # ---- 端子 ---------------------------------------------------------------
    bd.place("J3", SLOT[0], SLOT[1], 0)       # 1 番ピンが左 (ブラケットの側)、A 面が上、B 面が下
    bd.place("J1", JX, J1Y, 90)               # 口が右を向く
    bd.place("J2", JX, J2Y, 90)
    bd.place("J4", 68.5, 11.23, 90)           # 奇数のピンの列が右 (J1 の側)。上から 9 7 5 3 1
    bd.place("JP1", 26.6, 6.2, pin1="E")
    bd.place("JP5", 26.6, 9.0, pin1="E")      # JP1 に並列のはんだジャンパー (最初から閉じている)
    bd.place("JP2", 12.6, 39.4, pin1="E")
    bd.place("J5", 43.9, 42.3, pin1="W")
    bd.place("JP7", 52.25, 41.9, pin1="N")    # 12V の強制オン (はんだでつなぐ。スライドスイッチの代わり)
    bd.place("JP6", 12.6, 42.2, pin1="E")     # JP2 に並列のはんだジャンパー (最初から閉じている)

    # ---- ① USB-C のまわり ---------------------------------------------------
    bd.place("U5", 74.5, 12.5, 180)           # 1 (IO1) が左上、3 (IO2) が左下
    bd.place("JP3", 73.0, 16.4, pin1="W")
    bd.place("U1", 75.5, 23.6, 270)           # 1 番ピンが左上
    bd.place("C1", 69.9, 21.6, pin1="E")
    bd.place("R1", 81.0, 22.6, pin1="W")
    bd.place("R28", 76.0, 19.95, pin1="W")
    bd.place("R29", 79.9, 19.95, pin1="W")
    bd.place("R21", 81.2, 24.6, pin1="W")
    bd.place("C23", 81.2, 26.4, pin1="W")
    bd.place("R22", 76.6, 27.25, pin1="E")
    bd.place("C24", 73.4, 27.25, pin1="E")
    bd.place("R3", 86.2, 20.6, pin1="W")
    bd.place("C2", 86.2, 22.5, pin1="W")
    bd.place("D1", 61.0, 20.5, pin1="E")      # アノードが右、カソード (帯) が左
    # ---- ② USB-C のまわり ---------------------------------------------------
    bd.place("U2", 75.5, J2Y, 270)
    bd.place("C3", 69.9, J2Y - 2.0, pin1="E")
    bd.place("R4", 81.0, J2Y - 1.0, pin1="W")
    bd.place("R30", 73.5, 38.9, pin1="W")
    bd.place("R31", 77.1, 38.9, pin1="W")
    bd.place("D2", 61.0, J2Y, pin1="E")
    # ---- VIN の幹のまわり ----------------------------------------------------
    bd.place("C4", 54.4, 12.7, pin1="E")
    bd.place("C5", 54.4, 15.0, pin1="E")
    bd.place("TP1", BUS, 28.3)
    bd.place("TP5", 44.0, 15.9)
    bd.place("R23", 54.8, 22.4, pin1="N")
    bd.place("R24", 54.8, 25.6, pin1="N")
    bd.place("C25", 53.0, 24.0, pin1="N")
    # 過電圧の遮断 (VIN が約 13V を超えたら Q2 のゲートを GND に引く)
    bd.place("D7", 51.0, 22.5, pin1="N")      # カソード (パッド 1、帯) が上 = VIN
    bd.place("R35", 51.2, 26.9, pin1="N")
    bd.place("R36", 53.6, 28.2, pin1="W")
    bd.place("Q4", 52.0, 30.8, 180)           # 左上が 1 B、左下が 2 E、右が 3 C
    bd.place("R34", 42.0, 27.5, pin1="N")
    # VBUS1 を読む分圧と、U3 の EN の分圧 (幹と、北まわりの VBUS1 の枝の間)
    bd.place("R8", 61.7, 6.3, pin1="E")
    bd.place("R9", 61.7, 8.1, pin1="W")
    bd.place("C15", 61.7, 9.9, pin1="W")
    bd.place("D5", 61.7, 12.1, pin1="E")      # カソード (パッド 1、帯) が右
    bd.place("R25", 61.7, 14.3, pin1="E")
    bd.place("R26", 61.7, 16.1, pin1="W")
    bd.place("C26", 61.7, 17.9, pin1="W")
    # ---- 5V の LDO ----------------------------------------------------------
    bd.place("U6", 65.0, 26.0, 0)             # 左が 2 VIN、右上が 3 VOUT、右下が 1 GND
    bd.place("C6", 59.3, 24.3, pin1="W")
    bd.place("C7", 69.0, 25.9, pin1="N")
    bd.place("TP4", P5X, 37.4)
    # ---- 3.3V の降圧 --------------------------------------------------------
    bd.place("U3", U3X, U3Y, 0)               # 右の列が上から 4 GND・3 VIN・2 EN・1 RT、左の列が 5 SW・6 BST・7 SS・8 FB
    bd.place("C10", U3X + 2.15, U3Y - 0.5, pin1="S")
    bd.place("C8", U3X + 4.1, U3Y - 0.4, pin1="S")
    bd.place("C9", U3X + 6.5, U3Y - 0.4, pin1="S")
    bd.place("C11", U3X - 2.4, U3Y - 0.75, pin1="S")
    bd.place("L1", U3X - 7.7, U3Y - 3.5, pin1="E")
    bd.place("C12", U3X - 2.2, U3Y + 2.2, pin1="E")
    bd.place("R7", U3X - 1.4, U3Y + 3.9, pin1="E")
    bd.place("R6", U3X + 2.2, U3Y + 3.9, pin1="E")
    bd.place("C13", 33.3, 5.2, pin1="S")
    bd.place("C14", 30.9, 5.2, pin1="S")
    bd.place("C27", 22.0, 13.0, pin1="S")
    bd.place("C28", 19.8, 13.1, pin1="S")
    bd.place("JP4", 18.6, 29.1, pin1="E")
    bd.place("TP2", 28.6, 15.6)
    bd.place("R10", 11.4, 13.4, pin1="E")
    bd.place("LED3", 11.4, 15.6, pin1="E")
    # PERST# の遅延 (スロットの右を回る +3V3 の枝のすぐ右)
    bd.place("R27", 35.6, 16.2, pin1="W")
    bd.place("D6", 35.9, 14.3, pin1="W")      # カソード (パッド 1、帯) が左 = +3V3
    bd.place("C31", 39.5, 16.5, pin1="W")
    # ---- 12V の昇圧と出力スイッチ -------------------------------------------
    bd.place("U4", U4X, U4Y, 180)             # 左の列が上から 1 SW・2 GND・3 FB、右の列が 6 NC・5 VIN・4 EN
    bd.place("L2", U4X - 3.4, U4Y - 6.55, pin1="E")
    bd.place("D4", U4X - 5.6, U4Y - 1.5, pin1="W")   # カソード (パッド 1、帯) が左
    bd.place("C16", U4X + 4.05, U4Y - 0.6, pin1="N")
    bd.place("C17", U4X + 6.2, U4Y - 0.6, pin1="N")
    bd.place("C18", 28.5, 41.78, pin1="W")    # D4 のカソードと U4 の GND のすぐ下
    bd.place("C19", 24.2, 41.78, pin1="E")
    bd.place("R12", 33.4, 43.67, pin1="W")
    bd.place("R11", 30.2, 43.67, pin1="W")
    bd.place("R13", 38.9, 26.0, pin1="E")
    bd.place("Q1", 22.2, 38.9, 0)             # 右上が 2 S、右下が 1 G、左が 3 D
    bd.place("F1", 17.85, 39.4, pin1="E")
    bd.place("R14", 19.6, 42.0, pin1="W")
    bd.place("C20", 19.6, 43.67, pin1="W")
    bd.place("C32", 16.4, 42.0, pin1="W")
    bd.place("R15", 16.4, 43.67, pin1="E")
    bd.place("Q2", 12.6, 45.3, 0)
    bd.place("Q3", 18.2, 33.6, 180)           # 左上が 1 G (+3V3)、左下が 2 S (GND)、右が 3 D
    bd.place("R16", 9.3, 43.67, pin1="E")
    bd.place("C29", 8.7, 31.2, pin1="E")
    bd.place("C30", 9.3, 33.4, pin1="E")
    bd.place("R18", 9.3, 35.2, pin1="E")
    bd.place("R32", 13.9, 33.2, pin1="W")
    bd.place("R33", 13.9, 34.95, pin1="E")
    bd.place("C33", 13.9, 36.7, pin1="E")
    bd.place("TP3", 8.4, 37.3)
    # ---- マイコン -----------------------------------------------------------
    bd.place("U7", 46.5, 29.0, 0)             # 下の列が左から 1..10、上の列が左から 20..11
    bd.place("C21", 48.1, 34.5, pin1="E")
    bd.place("C22", 51.3, 34.5, pin1="W")
    bd.place("R19", 52.25, 38.3, pin1="N")
    bd.place("R20", 58.3, 39.1, pin1="N")
    bd.place("LED5", 58.3, 42.4, pin1="N")
    return bd


def route(bd: Board):
    """電源・USB・うらの GND を切りやすい長い制御線を手で引く。残りの細い信号は freerouting に任せる。"""
    P = bd.P
    T = bd.track

    # ======== USB のデータ線 (J1 -> U5 -> J4) =================================
    # J1 のパッドは上から CC2 11.75 / (A8) / D+ B6 12.75 / D- A7 13.25 / D+ A6 13.75 / D- B7 14.25 / CC1 14.75
    dp6, dn7, dp_a6, dn_b7 = P("J1", "B6"), P("J1", "A7"), P("J1", "A6"), P("J1", "B7")
    io1, io2 = P("U5", "1"), P("U5", "3")           # 左上、左下
    j4_5, j4_3 = P("J4", "5"), P("J4", "3")
    w0, w1 = 0.2, 0.5
    yp, yn = io1[1] - 0.85, io2[1] + 0.85            # U5 の使わないパッド (IO4・IO3) の外を回る
    # D+ : B6 から。0.5mm 上の列 (A8 は未使用) に寄せてから左へ。U5 の IO1 に触れて J4 の 5 番へ
    T("USB_DP", w0, [dp6, (82.5, dp6[1]), (82.0, dp6[1] - 0.5), (77.9, dp6[1] - 0.5), (76.35, yp)])
    T("USB_DP", w1, [(76.35, yp), (74.2, yp), (io1[0] + 0.2, io1[1]), io1, (72.4, io1[1]), (71.0, j4_5[1]), j4_5])
    # D- : A7 から。D+ と同じ長さになるよう、寄せる位置だけ 0.6mm ずらす
    T("USB_DN", w0, [dn7, (81.9, dn7[1]), (81.4, dn7[1] - 0.5), (77.9, dn7[1] - 0.5), (76.35, yn)])
    T("USB_DN", w1, [(76.35, yn), (74.2, yn), (io2[0] + 0.2, io2[1]), io2, (72.4, io2[1]), (71.0, j4_3[1]), j4_3])
    # 裏返しに挿したとき用の D+ (A6): ビアで裏へ回り、D- の下をくぐって D+ に合流
    va = (79.4, dp_a6[1])
    vb = (79.4, 11.5)
    T("USB_DP", w0, [dp_a6, va])
    bd.via("USB_DP", *va)
    T("USB_DP", w0, [va, vb], layer=B)
    bd.via("USB_DP", *vb)
    T("USB_DP", w0, [vb, (79.4, dp6[1] - 0.5)])
    # 裏返しに挿したとき用の D- (B7): おもてのまま、A6 のビアの外を回って D- に合流
    T("USB_DN", w0, [dn_b7, (81.9, dn_b7[1]), (81.5, dn_b7[1] + 0.4), (77.3, dn_b7[1] + 0.4), (76.9, yn - 0.1),
                     (76.35, yn)])
    bd.gnd_via(74.45, 12.5, frm=P("U5", "2"), width=0.4)
    # J4: 2 番も VBUS、8 番も GND (2 列めに挿すケーブルでも電源が届く)
    T("USBH_VBUS", 0.5, [P("J4", "1"), P("J4", "2")])
    T("GND", 0.5, [P("J4", "7"), P("J4", "8")])

    # ======== VBUS1 (J1 の 2 つのパッド -> D1) ================================
    vn, vs = P("J1", "B4A9"), P("J1", "A4B9")       # 上のパッド、下のパッド
    d1a, d1k = P("D1", "1"), P("D1", "2")
    # 北まわり: J4 の上を回って D1 へ
    T("VBUS1", 0.6, [vn, (81.1, vn[1]), (81.1, 8.4)])
    T("VBUS1", 1.0, [(81.1, 8.4), (81.1, 5.2), (80.2, 4.3), (66.1, 4.3), (65.2, 5.2), (65.2, 18.4), (64.4, 19.4),
                     (64.4, d1a[1]), d1a])
    # 南まわり: J4 の下を通って D1 へ
    T("VBUS1", 0.6, [vs, (81.0, vs[1]), (80.0, vs[1] + 1.0)])
    T("VBUS1", 1.0, [(80.0, vs[1] + 1.0), (78.5, 18.4), (66.3, 18.4), (65.2, 19.4), (64.4, 19.4)])
    for ref in ("R8", "R25"):                                     # EN の分圧と、マイコンが読む分圧へ
        p = P(ref, "1")
        T("VBUS1", 0.4, [p, (65.2, p[1])])
    p = P("R28", "1")
    T("VBUS1", 0.4, [p, (p[0], 18.4)])                            # ブリーダ抵抗へ
    p = P("R29", "1")
    T("VBUS1", 0.4, [p, (p[0], 17.8)])
    u1_1 = P("U1", "1")
    T("VBUS1", 0.5, [(u1_1[0], 18.4), u1_1])                      # U1 の VHV (1 番) と 1µF
    T("VBUS1", 0.5, [P("C1", "1"), u1_1])
    bd.zone("VBUS1", F, rect(62.4, 19.0, 66.9, 22.2), clearance=0.2, thermal=False, name="D1-anode")
    bd.zone("VBUS1", B, rect(62.6, 18.7, 67.5, 22.5), clearance=0.3, thermal=False, name="D1-anode-bottom")
    for vx, vy in ((65.6, 19.9), (65.6, 21.3), (64.5, 21.6), (66.6, 20.6)):
        bd.via("VBUS1", vx, vy, dia=0.8, drill=0.4)

    # ======== VBUS2 (J2 の 2 つのパッド -> D2)。U2 を囲む輪 ====================
    vn2, vs2 = P("J2", "B4A9"), P("J2", "A4B9")
    d2a, d2k = P("D2", "1"), P("D2", "2")
    yn2, ys2 = J2Y - 4.0, J2Y + 4.0
    T("VBUS2", 0.6, [vn2, (81.4, vn2[1]), (80.8, vn2[1] - 0.6)])
    T("VBUS2", 1.0, [(80.8, vn2[1] - 0.6), (79.8, yn2), (67.5, yn2), (64.6, d2a[1] - 1.1), (64.6, d2a[1]), d2a])
    T("VBUS2", 0.6, [vs2, (81.4, vs2[1]), (80.8, vs2[1] + 0.6)])
    T("VBUS2", 1.0, [(80.8, vs2[1] + 0.6), (79.8, ys2), (67.5, ys2), (64.6, d2a[1] + 1.1), (64.6, d2a[1])])
    u2_1 = P("U2", "1")
    T("VBUS2", 0.5, [(u2_1[0], yn2), u2_1])
    T("VBUS2", 0.5, [P("C3", "1"), u2_1])
    for ref in ("R30", "R31"):
        p = P(ref, "1")
        T("VBUS2", 0.4, [(p[0], ys2), p])
    bd.zone("VBUS2", F, rect(62.4, J2Y - 1.7, 66.6, J2Y + 1.7), clearance=0.2, thermal=False, name="D2-anode")
    bd.zone("VBUS2", B, rect(62.6, J2Y - 1.6, 72.3, 46.0), clearance=0.3, thermal=False, name="D2-anode-bottom")
    for vx, vy in ((65.6, J2Y - 0.9), (65.6, J2Y + 0.9), (64.6, J2Y + 0.0), (65.5, J2Y + 2.1), (66.4, J2Y + 3.0),
                   (68.5, ys2), (70.5, ys2)):
        bd.via("VBUS2", vx, vy, dia=0.8, drill=0.4)
    # USB-C の GND のパッド: 1 つにつきビア 2 個
    for j in ("J1", "J2"):
        for num, s in (("B1A12", -1), ("A1B12", 1)):
            g = P(j, num)
            T("GND", 0.5, [(g[0] - 0.4, g[1]), (82.25, g[1] + 0.4 * s), (82.3, g[1] + 1.2 * s)])
            bd.via("GND", 82.25, g[1] + 0.4 * s)
            bd.via("GND", 82.3, g[1] + 1.2 * s)

    # ======== VIN の幹 ========================================================
    c9, c8, c10 = P("C9", "1"), P("C8", "1"), P("C10", "1")
    yv = c9[1]
    T("VIN", 2.0, [(BUS, yv), (BUS, d2k[1])])                     # 縦の幹 (D1・D2 のカソードが乗る)
    T("VIN", 1.5, [d1k, (BUS, d1k[1])])
    T("VIN", 1.5, [d2k, (BUS, d2k[1])])
    T("VIN", 1.5, [(BUS, yv), c9, c8])                            # 降圧の入力コンデンサへ
    T("VIN", 0.8, [c8, (c10[0] + 0.3, yv), c10])
    u3_3 = P("U3", "3")
    T("VIN", 0.3, [u3_3, (c10[0] - 0.25, u3_3[1]), (c10[0], u3_3[1] + 0.25)])
    for ref in ("C4", "C5"):
        p = P(ref, "1")
        T("VIN", 1.0, [p, (BUS, p[1])])
    p = P("R23", "1")
    T("VIN", 0.4, [p, (p[0], 20.0)])
    p = P("C6", "1")
    T("VIN", 0.6, [p, (BUS, p[1])])
    u6_2 = P("U6", "2")
    T("VIN", 0.6, [(BUS, u6_2[1]), u6_2])
    bd.zone("VIN", F, rect(56.5, 18.9, 59.7, 22.2), clearance=0.2, thermal=False, name="D1-cathode")
    bd.zone("VIN", F, rect(56.5, J2Y - 1.7, 59.7, J2Y + 1.7), clearance=0.2, thermal=False, name="D2-cathode")
    # 昇圧へ: 幹から左へ、スロットの右を下へ
    xb = U4X + 2.8
    l2v = P("L2", "1")
    c16 = P("C16", "1")
    T("VIN", 1.5, [(BUS, 20.0), (xb + 0.6, 20.0), (xb, 20.6), (xb, c16[1])])
    T("VIN", 1.5, [(xb, l2v[1]), l2v])
    T("VIN", 1.0, [(xb, c16[1]), c16, P("C17", "1")])
    u4_5 = P("U4", "5")
    T("VIN", 0.5, [(xb, c16[1]), (xb, u4_5[1] - 0.45), (xb - 0.45, u4_5[1]), u4_5])

    # ======== 3.3V の降圧のまわり =============================================
    u3 = {n: P("U3", n) for n in "12345678"}
    c11s, c11b = P("C11", "2"), P("C11", "1")
