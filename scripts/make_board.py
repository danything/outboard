# うらの GND を切らせたくない所 (うらの配線を禁止): 降圧・昇圧・USB のデータ線の下
NO_BOTTOM = {
    "buck-gnd": (U3X - 7.6, U3Y - 5.8, U3X + 18.0, U3Y + 7.0),
    "boost-gnd": (U4X - 7.4, U4Y - 4.2, U4X + 9.0, U4Y + 10.3),
    "usb-gnd-1": (JX + 7.12, J1Y - 1.3, JX + 13.6, J1Y + 3.2),
    "usb-gnd-2": (JX + 13.6, J1Y - 0.65, J4X + 3.0, J1Y + 2.6),
}


def keepouts(bd: Board):
    """自動配線に通らせたくない所。"""
    for name, box in NO_BOTTOM.items():
        bd.keepout([B], rect(*box), name=name)
    with bd.frame(**USB1):
        bd.keepout([B], rect(80.0, 10.9, 82.5, 15.7), name="usb-gnd-0")
    # USB-C の殻の下: ビアを置かせない。おもての線も通さない (CC の線が殻の下へ入らないように)
    for name, y in (("J1", J1Y), ("J2", J2Y)):
        bd.keepout([F, B], rect(0.1, y - 3.7, 5.75, y + 3.7), tracks=False, vias=True, name=name + "-shell-no-via")
        bd.keepout([F], rect(0.1, y - 3.6, 5.6, y + 3.6), name=name + "-shell-no-top-track")
    # D1・D2 の胴体の下: おもての線を禁止
    for name in ("D1", "D2"):
        k = bd.P(name, "2")
        bd.keepout([F], rect(k[0] - 3.75, k[1] - 0.9, k[0] - 1.25, k[1] + 0.9), name=name + "-body")


def drawing(bd: Board):
    """ブラケット・カード・コネクタの口・J4 のプラグ・USB-C の口を Dwgs.User の層に描く (推定の値は est と書く)。"""
    D = pcbnew.Dwgs_User
    x_out, x_in = MOUTH, MOUTH + BRACKET_T

    def box(x1, y1, x2, y2, w=0.1):
        for a, b_ in (((x1, y1), (x2, y1)), ((x2, y1), (x2, y2)), ((x2, y2), (x1, y2)), ((x1, y2), (x1, y1))):
            bd.line(D, a[0], a[1], b_[0], b_[1], w)

    def note(s, x, y, rot=0, just="L"):
        bd.text(s, x, y, size=0.8, thick=0.1, layer=D, rot=rot, just=just)

    # ブラケットの板 (上から見た形: 厚み 0.86 の線)。全幅は y <= 7.68、舌の先は 14.95 (標準)・10.85 (ロープロファイル)
    box(x_out, CARD_EDGE_Y - 3.0, x_in, BRACKET_FULL_Y)
    box(x_out, BRACKET_FULL_Y, x_in, TONGUE_Y, 0.05)
    bd.line(D, x_out - 1.5, TONGUE_Y_LP, x_in + 0.6, TONGUE_Y_LP, 0.05)
    bd.line(D, x_out - 1.5, TONGUE_Y, x_in + 0.6, TONGUE_Y, 0.05)
    bd.line(D, x_out - 1.5, BRACKET_FULL_Y, x_in + 0.6, BRACKET_FULL_Y, 0.05)
    bd.line(D, x_out, CARD_EDGE_Y - 5.0, x_out, H + 2.0, 0.05)        # ブラケットの外の面 = USB-C の口の面
    note("bracket (est): plate x -0.99..-0.13, z -2.06..+16.36", x_out - 0.6, 7.0, rot=90)
    note("full width to y 7.68, tongue tip y 14.95 (LP 10.85), tongue z +2.05..+12.24 (est)", x_out - 2.0, 15.5, rot=90)
    # カード (基板と同じ平面。下の辺は y = -13.0) とコネクタの口 (y = -8.1)
    px = SLOT[0] - 9.5
    cx = px - CARD_END
    bd.line(D, cx, CARD_EDGE_Y, W + 4.0, CARD_EDGE_Y, 0.1)
    bd.line(D, cx, CARD_EDGE_Y, cx, CARD_EDGE_Y - 3.0, 0.1)
    note("card lower edge y -13.0 (est)", 2.0, CARD_EDGE_Y - 1.0)
    box(SLOT[0] - 15.45, MOUTH_Y, SLOT[0] + 15.45, 0.0)
    note("J3 body, mouth y -8.1 (est)", SLOT[0] - 14.5, -4.0)
    bd.line(D, px, MOUTH_Y - 2.0, px, 6.0, 0.05)                     # 1 番ピンの中心
    note("pin 1", px + 0.3, MOUTH_Y - 1.2)
    for x1, x2 in EARS:                                               # 耳の下 (両面とも部品を置かない)
        box(x1, 0.0, x2, EAR_Y, 0.05)
    note("ear (est)", EARS[0][0] + 0.3, EAR_Y - 0.7)
    # J4 の樹脂とプラグ (プラグの下は部品を置かない)
    box(*J4_BODY)
    box(*J4_PLUG, 0.05)
    bd.line(D, J4_PLUG[0], J4_PLUG[1], J4_PLUG[2], J4_PLUG[3], 0.05)
    bd.line(D, J4_PLUG[0], J4_PLUG[3], J4_PLUG[2], J4_PLUG[1], 0.05)
    note("J4 plug 14 x 13.2 (est), no parts below", J4_PLUG[0] + 0.4, J4_PLUG[1] + 1.0)
    for jy in (J1Y, J2Y):                                             # USB-C の口 (幅 8.94mm)
        bd.line(D, MOUTH, jy - 4.47, MOUTH, jy + 4.47, 0.2)
        bd.line(D, MOUTH, jy - 4.47, 0.0, jy - 4.47, 0.1)
        bd.line(D, MOUTH, jy + 4.47, 0.0, jy + 4.47, 0.1)


def main():
    bd = build()
    route(bd)
    keepouts(bd)
    drawing(bd)
    os.makedirs(os.path.join(ROOT, "build"), exist_ok=True)
