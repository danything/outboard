"""基板を組み立てる (1 段目): 外形・部品の配置・電源と USB の手配線・GND のビア・シルク。

出力: build/pre_route.kicad_pcb (自動配線の前の基板)
このあと scripts/route.sh (freerouting) と scripts/finish_board.py (取り込み・ベタ・仕上げ) を実行する。

座標は基板の左上の角を (0, 0) とした mm。x は右、y は下。基板は 90 x 45mm。
左の辺 (x = 0) がカードのブラケットの側、右の辺 (x = 90) に USB-C が 2 つ。

使い方: "C:\\Program Files\\KiCad\\10.0\\bin\\python.exe" scripts/make_board.py
"""
from __future__ import annotations

import os
import shutil
import sys

import pcbnew

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from board_lib import B, F, ROOT, Board, rect  # noqa: E402

W, H, R = 90.0, 45.0, 3.0

# --- 配置の基準になる座標 ---------------------------------------------------
J1Y, J2Y = 13.5, 32.9          # USB-C の中心の y
JX = 85.92                      # USB-C の原点の x。基板の端 (x=90) は、後ろの殻の穴から 5.79mm (データシートの図)
BUS = 57.5                      # VIN の幹 (縦) の x
U3X, U3Y = 47.0, 9.0            # 降圧 IC
U4X, U4Y = 33.5, 40.65          # 昇圧 IC
SLOT = (17.6, 22.5)             # PCIe スロット


def build() -> Board:
    bd = Board()

    # ---- 外形 (角の丸い四角) と取り付け穴 -----------------------------------
    E = pcbnew.Edge_Cuts
    bd.line(E, R, 0, W - R, 0, 0.1)
    bd.line(E, W, R, W, H - R, 0.1)
    bd.line(E, W - R, H, R, H, 0.1)
    bd.line(E, 0, H - R, 0, R, 0.1)
    bd.arc(E, R, R, R, 180, 270, 0.1)
    bd.arc(E, W - R, R, R, 270, 360, 0.1)
    bd.arc(E, W - R, H - R, R, 0, 90, 0.1)
    bd.arc(E, R, H - R, R, 90, 180, 0.1)
    for ref, x, y in (("H1", 3.5, 3.5), ("H2", W - 3.5, 3.5), ("H3", 3.5, H - 3.5), ("H4", W - 3.5, H - 3.5)):
        bd.place(ref, x, y)

    # ---- 端子 ---------------------------------------------------------------
    bd.place("J3", SLOT[0], SLOT[1], 0)       # 1 番ピンが左 (ブラケットの側)、A 面が上、B 面が下
    bd.place("J1", JX, J1Y, 90)               # 口が右を向く
    bd.place("J2", JX, J2Y, 90)
    bd.place("J4", 68.5, 11.23, 90)           # 奇数のピンの列が右 (J1 の側)。上から 9 7 5 3 1
    bd.place("JP1", 26.6, 6.2, pin1="E")
    bd.place("JP2", 12.6, 39.4, pin1="E")
    bd.place("J5", 43.9, 42.3, pin1="W")
    bd.place("SW1", 51.5, 42.6, 0)            # つまみが下の辺から出る

    # ---- ① USB-C のまわり ---------------------------------------------------
    bd.place("U5", 74.5, 12.5, 180)
    bd.place("JP3", 73.0, 16.4, pin1="W")
    bd.place("U1", 75.5, 23.6, 270)           # 1 番ピンが左上
    bd.place("C1", 69.9, 21.6, pin1="E")
    bd.place("R1", 81.0, 22.6, pin1="W")
    bd.place("R2", 76.0, 19.95, pin1="W")
    bd.place("LED1", 79.6, 19.95, pin1="W")
    bd.place("R21", 81.2, 24.6, pin1="W")
    bd.place("C23", 81.2, 26.4, pin1="W")
    bd.place("R22", 76.6, 27.25, pin1="E")
    bd.place("C24", 73.4, 27.25, pin1="E")
    bd.place("R3", 86.2, 20.6, pin1="W")
    bd.place("C2", 86.2, 22.5, pin1="W")
    bd.place("D1", 61.0, 20.5, pin1="E")      # アノードが右
    # ---- ② USB-C のまわり ---------------------------------------------------
    bd.place("U2", 75.5, J2Y, 270)
    bd.place("C3", 69.9, J2Y - 2.0, pin1="E")
    bd.place("R4", 81.0, J2Y - 1.0, pin1="W")
    bd.place("R5", 73.5, 38.9, pin1="W")
    bd.place("LED2", 77.1, 38.9, pin1="W")
    bd.place("D2", 61.0, J2Y, pin1="E")
    # ---- VIN の幹のまわり ----------------------------------------------------
    bd.place("C4", 54.4, 12.7, pin1="E")
    bd.place("C5", 54.4, 15.0, pin1="E")
    bd.place("D3", 54.3, 17.3, pin1="W")      # カソード (パッド 2) が右 = VIN
    bd.place("TP1", BUS, 28.3)
    bd.place("TP5", 50.6, 16.8)
    bd.place("R23", 54.5, 23.0, pin1="E")
    bd.place("R24", 54.5, 24.8, pin1="E")
    bd.place("C25", 54.5, 26.6, pin1="E")
    # VBUS1 を読む分圧と、U3 の EN の分圧 (幹と、北まわりの VBUS1 の枝の間)
    bd.place("R8", 61.7, 6.3, pin1="E")
    bd.place("R9", 61.7, 8.1, pin1="W")
    bd.place("C15", 61.7, 9.9, pin1="W")
    bd.place("D5", 61.7, 12.1, pin1="E")      # カソード (パッド 1) が右
    bd.place("R25", 61.7, 14.3, pin1="E")
    bd.place("R26", 61.7, 16.1, pin1="W")
    bd.place("C26", 61.7, 17.9, pin1="W")
    # ---- 5V の LDO ----------------------------------------------------------
    bd.place("U6", 65.0, 26.0, 0)             # 左が 2 VIN、右上が 3 VOUT、右下が 1 GND
    bd.place("C6", 59.3, 24.3, pin1="W")
    bd.place("C7", 69.0, 25.9, pin1="N")
    bd.place("TP4", 55.2, 37.4)
    # ---- 3.3V の降圧 --------------------------------------------------------
    bd.place("U3", U3X, U3Y, 0)               # 右の列が上から 4 GND・3 VIN・2 EN・1 RT、左の列が 5 SW・6 BST・7 SS・8 FB
    bd.place("C10", U3X + 2.15, U3Y - 0.5, pin1="S")
    bd.place("C8", U3X + 4.1, U3Y - 0.4, pin1="S")
    bd.place("C9", U3X + 6.5, U3Y - 0.4, pin1="S")
    bd.place("C11", U3X - 2.4, U3Y - 0.75, pin1="S")
    bd.place("L1", U3X - 7.7, U3Y - 3.5, pin1="E")
    bd.place("C12", U3X - 2.2, U3Y + 2.2, pin1="E")
    bd.place("R7", U3X - 1.4, U3Y + 3.9, pin1="E")
    bd.place("R6", U3X + 2.2, U3Y + 3.9, pin1="E")
    bd.place("C13", 33.3, 5.2, pin1="S")
    bd.place("C14", 30.9, 5.2, pin1="S")
    bd.place("C27", 22.0, 13.0, pin1="S")
    bd.place("C28", 19.8, 13.1, pin1="S")
    bd.place("R27", 17.7, 13.1, pin1="S")
    bd.place("C31", 15.4, 12.9, pin1="S")
    bd.place("JP4", 18.6, 29.1, pin1="E")
    bd.place("TP2", 28.6, 15.6)
    bd.place("R10", 11.4, 13.4, pin1="E")
    bd.place("LED3", 11.4, 15.6, pin1="E")
    # ---- 12V の昇圧と出力スイッチ -------------------------------------------
    bd.place("U4", U4X, U4Y, 180)             # 左の列が上から 1 SW・2 GND・3 FB、右の列が 6 NC・5 VIN・4 EN
    bd.place("L2", U4X - 3.4, U4Y - 6.45, pin1="E")
    bd.place("D4", U4X - 5.6, U4Y - 1.4, pin1="W")   # カソード (パッド 1) が左
    bd.place("C16", U4X + 4.05, U4Y - 0.6, pin1="N")
    bd.place("C17", U4X + 6.2, U4Y - 0.6, pin1="N")
    bd.place("C18", 23.0, 39.5, pin1="N")
    bd.place("C19", 20.6, 39.5, pin1="N")
    bd.place("R12", 31.4, 43.6, pin1="E")
    bd.place("R11", 26.0, 42.55, pin1="W")
    bd.place("R13", 35.9, 43.6, pin1="W")
    bd.place("Q1", 17.3, 39.4, 0)             # 右上が 2 S、右下が 1 G、左が 3 D
    bd.place("C20", 17.0, 42.0, pin1="E")
    bd.place("R14", 17.0, 43.75, pin1="E")
    bd.place("R15", 20.6, 43.75, pin1="W")
    bd.place("Q2", 12.4, 43.0, 0)
    bd.place("R16", 9.0, 43.6, pin1="E")
    bd.place("C29", 8.7, 31.2, pin1="E")
    bd.place("C30", 9.3, 33.4, pin1="E")
    bd.place("R18", 9.3, 35.2, pin1="E")
    bd.place("R17", 13.9, 33.2, pin1="W")
    bd.place("LED4", 13.9, 34.95, pin1="E")
    bd.place("TP3", 8.4, 37.3)
    # ---- マイコン -----------------------------------------------------------
    bd.place("U7", 46.5, 29.0, 0)             # 下の列が左から 1..10、上の列が左から 20..11
    bd.place("C21", 48.1, 34.5, pin1="E")
    bd.place("C22", 51.3, 34.5, pin1="W")
    bd.place("R19", 52.25, 38.3, pin1="N")
    bd.place("R20", 58.3, 39.1, pin1="N")
    bd.place("LED5", 58.3, 42.4, pin1="N")
    return bd


def route(bd: Board):
    """電源と USB のデータ線を手で引く。細い信号は freerouting に任せる。"""
    P = bd.P
    T = bd.track

    # ======== USB のデータ線 (J1 -> U5 -> J4) =================================
    # J1 のパッドは上から CC2 11.75 / (A8) / D+ B6 12.75 / D- A7 13.25 / D+ A6 13.75 / D- B7 14.25 / CC1 14.75
    dp6, dn7, dp_a6, dn_b7 = P("J1", "B6"), P("J1", "A7"), P("J1", "A6"), P("J1", "B7")
    u5_6, u5_1, u5_4, u5_3 = P("U5", "6"), P("U5", "1"), P("U5", "4"), P("U5", "3")
    j4_5, j4_3 = P("J4", "5"), P("J4", "3")
    w0, w1 = 0.2, 0.5
    # D+ : B6 から。0.5mm 上の列 (A8 は未使用) に寄せてから左へ
    T("USB_DP", w0, [dp6, (82.5, dp6[1]), (82.0, dp6[1] - 0.5), (77.6, dp6[1] - 0.5), (76.9, u5_6[1]), u5_6])
    T("USB_DP", w1, [u5_6, u5_1])
    T("USB_DP", w1, [u5_1, (72.4, u5_1[1]), (71.0, j4_5[1]), j4_5])
    # D- : A7 から。D+ と同じ長さになるよう、寄せる位置だけ 0.6mm ずらす
    T("USB_DN", w0, [dn7, (81.9, dn7[1]), (81.4, dn7[1] - 0.5), (77.6, dn7[1] - 0.5), (76.9, u5_4[1]), u5_4])
    T("USB_DN", w1, [u5_4, u5_3])
    T("USB_DN", w1, [u5_3, (72.4, u5_3[1]), (71.0, j4_3[1]), j4_3])
    # 裏返しに挿したとき用の D+ (A6): ビアで裏へ回り、D- の下をくぐって D+ に合流
    va = (79.4, dp_a6[1])
    vb = (79.4, 11.5)
    T("USB_DP", w0, [dp_a6, va])
    bd.via("USB_DP", *va)
    T("USB_DP", w0, [va, vb], layer=B)
    bd.via("USB_DP", *vb)
    T("USB_DP", w0, [vb, (79.4, dp6[1] - 0.5)])
    # 裏返しに挿したとき用の D- (B7): おもてのまま、A6 のビアの外を回って D- に合流
    T("USB_DN", w0, [dn_b7, (81.9, dn_b7[1]), (81.5, dn_b7[1] + 0.4), (79.0, dn_b7[1] + 0.4), (77.8, u5_4[1]),
                     (76.9, u5_4[1])])
    # U5 の GND
    bd.gnd_via(74.45, 12.5, frm=P("U5", "2"), width=0.4)

    # ======== VBUS1 (J1 の 2 つのパッド -> D1) ================================
    vn, vs = P("J1", "B4A9"), P("J1", "A4B9")       # 上のパッド、下のパッド
    d1a, d1k = P("D1", "1"), P("D1", "2")
    # 北まわり: J4 の上を回って D1 へ
    T("VBUS1", 0.6, [vn, (81.3, vn[1]), (81.3, 8.6)])
    T("VBUS1", 1.0, [(81.3, 8.6), (81.3, 5.2), (80.4, 4.3), (66.1, 4.3), (65.2, 5.2), (65.2, 18.4), (64.4, 19.4),
                     (64.4, d1a[1]), d1a])
    # 南まわり: J4 の下を通って D1 へ
    T("VBUS1", 0.6, [vs, (81.0, vs[1]), (80.0, vs[1] + 1.0)])
    T("VBUS1", 1.0, [(80.0, vs[1] + 1.0), (78.5, 18.4), (66.3, 18.4), (65.2, 19.4), (64.4, 19.4)])
    # EN の分圧 (R8) と、マイコンが読む分圧 (R25) へ
    for ref in ("R8", "R25"):
        p = P(ref, "1")
        T("VBUS1", 0.4, [p, (65.2, p[1])])
    p = P("R2", "1")
    T("VBUS1", 0.4, [p, (p[0], 18.4)])                            # LED1 の抵抗へ
    # U1 の VHV (1 番) と 1µF
    u1_1 = P("U1", "1")
    T("VBUS1", 0.5, [(u1_1[0], 18.4), u1_1])
    T("VBUS1", 0.5, [P("C1", "1"), u1_1])
    # J1 の GND のパッド
    g1, g2 = P("J1", "B1A12"), P("J1", "A1B12")
    bd.gnd_via(82.25, g1[1] - 0.4, frm=(g1[0] - 0.4, g1[1]), width=0.5)
    bd.gnd_via(82.25, g2[1] + 0.4, frm=(g2[0] - 0.4, g2[1]), width=0.5)

    # ======== VBUS2 (J2 の 2 つのパッド -> D2)。U2 を囲む輪 ====================
    vn, vs = P("J2", "B4A9"), P("J2", "A4B9")
    d2a, d2k = P("D2", "1"), P("D2", "2")
    yn, ys = J2Y - 4.0, J2Y + 4.0
    T("VBUS2", 0.6, [vn, (81.4, vn[1]), (80.8, vn[1] - 0.6)])
    T("VBUS2", 1.0, [(80.8, vn[1] - 0.6), (79.8, yn), (67.5, yn), (64.6, d2a[1] - 1.1), (64.6, d2a[1]), d2a])
    T("VBUS2", 0.6, [vs, (81.4, vs[1]), (80.8, vs[1] + 0.6)])
    T("VBUS2", 1.0, [(80.8, vs[1] + 0.6), (79.8, ys), (67.5, ys), (64.6, d2a[1] + 1.1), (64.6, d2a[1])])
    u2_1 = P("U2", "1")
    T("VBUS2", 0.5, [(u2_1[0], yn), u2_1])
    T("VBUS2", 0.5, [P("C3", "1"), u2_1])
    r5 = P("R5", "1")
    T("VBUS2", 0.4, [(r5[0], ys), r5])                            # LED2 の抵抗へ
    g1, g2 = P("J2", "B1A12"), P("J2", "A1B12")
    bd.gnd_via(82.25, g1[1] - 0.4, frm=(g1[0] - 0.4, g1[1]), width=0.5)
    bd.gnd_via(82.25, g2[1] + 0.4, frm=(g2[0] - 0.4, g2[1]), width=0.5)

    # ======== VIN の幹 ========================================================
    c9, c8, c10 = P("C9", "1"), P("C8", "1"), P("C10", "1")
    yv = c9[1]
    T("VIN", 2.0, [(BUS, yv), (BUS, d2k[1])])                     # 縦の幹 (D1・D2 のカソードが乗る)
    T("VIN", 1.5, [d1k, (BUS, d1k[1])])
    T("VIN", 1.5, [d2k, (BUS, d2k[1])])
    T("VIN", 1.5, [(BUS, yv), c9, c8])                            # 降圧の入力コンデンサへ
    T("VIN", 0.8, [c8, (c10[0] + 0.3, yv), c10])
    u3_3 = P("U3", "3")
    T("VIN", 0.3, [u3_3, (c10[0] - 0.25, u3_3[1]), (c10[0], u3_3[1] + 0.25)])
    for ref in ("C4", "C5"):
        p = P(ref, "1")
        T("VIN", 1.0, [p, (BUS, p[1])])
    p = P("D3", "2")
    T("VIN", 0.8, [p, (BUS, p[1])])
    p = P("R23", "1")
    T("VIN", 0.4, [p, (BUS, p[1])])
    p = P("C6", "1")
    T("VIN", 0.6, [p, (BUS, p[1])])
    u6_2 = P("U6", "2")
    T("VIN", 0.6, [(BUS, u6_2[1]), u6_2])
    # 昇圧へ: 幹から左へ、スロットの右を下へ
    xb = U4X + 2.8
    l2v = P("L2", "1")
    c16 = P("C16", "1")
    T("VIN", 1.5, [(BUS, 20.0), (xb + 0.6, 20.0), (xb, 20.6), (xb, c16[1])])
    T("VIN", 1.5, [(xb, l2v[1]), l2v])
    T("VIN", 1.0, [(xb, c16[1]), c16, P("C17", "1")])
    u4_5 = P("U4", "5")
    T("VIN", 0.5, [(xb, c16[1]), (xb, u4_5[1] - 0.45), (xb - 0.45, u4_5[1]), u4_5])

    # ======== 3.3V の降圧のまわり =============================================
    u3 = {n: P("U3", n) for n in "12345678"}
    c11s, c11b = P("C11", "2"), P("C11", "1")
    l1sw, l1out = P("L1", "1"), P("L1", "2")
    # SW: 5 番ピン -> C11 -> L1
    T("SW_3V3", 0.28, [u3["5"], (u3["5"][0] - 0.6, u3["5"][1]), (u3["5"][0] - 1.1, u3["5"][1] - 0.5)])
    T("SW_3V3", 0.6, [(u3["5"][0] - 1.1, u3["5"][1] - 0.5), (c11s[0] + 0.3, c11s[1]), c11s])
    T("SW_3V3", 0.8, [c11s, (l1sw[0] + 0.6, l1sw[1] + 1.0), l1sw])
    # BST: 6 番ピン -> C11
    T("BST_3V3", 0.2, [u3["6"], (c11b[0] + 0.2, u3["6"][1]), c11b])
    # SS: 7 番ピン -> C12
    c12 = P("C12", "1")
    T("SS_3V3", 0.2, [u3["7"], (c12[0] + 0.05, u3["7"][1]), (c12[0] + 0.05, c12[1] - 0.2), c12])
    bd.gnd_via(P("C12", "2")[0] - 1.1, c12[1], frm=P("C12", "2"))
    # FB: 8 番ピン -> R7・R6
    r7, r6 = P("R7", "1"), P("R6", "2")
    T("FB_3V3", 0.2, [u3["8"], (u3["8"][0], r7[1] - 0.6), r7])
    T("FB_3V3", 0.25, [r7, r6])
    bd.gnd_via(P("R7", "2")[0] - 1.1, r7[1], frm=P("R7", "2"))
    # EN: ピンから出る所だけ (続きは自動配線)
    e = u3["2"]
    T("EN_3V3", 0.2, [e, (e[0] + 0.7, e[1]), (e[0] + 0.7, e[1] + 1.7), (e[0] + 1.8, e[1] + 1.7)])
    # GND: 4 番ピン -> C10 の GND。入力コンデンサの GND にビア
    c10g = P("C10", "2")
    T("GND", 0.3, [u3["4"], (c10g[0] - 0.55, u3["4"][1]), (c10g[0], u3["4"][1] - 0.35)])
    T("GND", 1.0, [c10g, P("C8", "2"), P("C9", "2")])
    for x in (c10g[0], c10g[0] + 1.05, P("C8", "2")[0], P("C8", "2")[0] + 1.2, P("C9", "2")[0]):
        bd.gnd_via(x, c10g[1] - 1.45, frm=(x, c10g[1] - 0.3), width=0.5)
    # 出力: L1 -> C13・C14 -> JP1
    c13, c14 = P("C13", "1"), P("C14", "1")
    jp1a, jp1b = P("JP1", "1"), P("JP1", "2")
    T("+3V3_BUCK", 1.5, [(l1out[0], c13[1]), c13, c14])
    T("+3V3_BUCK", 1.5, [c14, jp1a])
    for ref in ("C13", "C14"):
        g = P(ref, "2")
        bd.gnd_via(g[0], g[1] - 1.5, frm=g, width=0.6)
    bd.gnd_via(P("C14", "2")[0] - 1.3, P("C14", "2")[1] - 0.9, frm=P("C14", "2"), width=0.6)
    # +3V3: JP1 -> 上の幹 -> A10・A9、右を回って B8
    a9, a10, b8 = P("J3", "A9"), P("J3", "A10"), P("J3", "B8")
    xt, yt = jp1b[0], 15.6
    T("+3V3", 2.0, [jp1b, (xt, yt), (a10[0], yt)])
    T("+3V3", 1.5, [(a10[0], yt), a10])
    T("+3V3", 1.0, [a10, a9])
    xr, yb = 32.4, 31.2
    T("+3V3", 2.0, [(xt, yt), (xr - 1.0, yt), (xr, yt + 1.0), (xr, yb - 1.0), (xr - 1.0, yb), (b8[0] + 0.9, yb)])
    T("+3V3", 1.5, [(b8[0] + 0.9, yb), (b8[0], yb - 0.9), b8])
    for ref in ("C27", "C28", "R27"):
        p = P(ref, "1")
        T("+3V3", 0.8 if ref != "R27" else 0.4, [p, (p[0], yt)])
    for ref in ("C27", "C28", "C31"):
        g = P(ref, "2")
        bd.gnd_via(g[0], g[1] - 1.4, frm=g, width=0.6)
    bd.gnd_via(P("C27", "2")[0] + 1.3, P("C27", "2")[1] - 0.9, frm=P("C27", "2"), width=0.6)
    p = P("JP4", "1")
    T("+3V3", 0.6, [p, (p[0], yb)])
    b10 = P("J3", "B10")
    q = P("JP4", "2")
    T("+3V3AUX", 0.4, [q, (b10[0], q[1] - 0.9), b10])

    # ======== 12V の昇圧のまわり ==============================================
    u4 = {n: P("U4", n) for n in "123456"}
    d4k, d4a = P("D4", "1"), P("D4", "2")
    l2sw = P("L2", "2")
    T("SW_12V", 0.6, [u4["1"], (d4a[0] + 0.5, u4["1"][1]), d4a])
    T("SW_12V", 1.5, [d4a, (d4a[0] - 0.4, d4a[1] - 1.2), (l2sw[0] + 0.2, l2sw[1] + 1.3), l2sw])
    c18, c19 = P("C18", "1"), P("C19", "1")
    q1s, q1d = P("Q1", "2"), P("Q1", "3")
    T("+12V_BOOST", 1.2, [d4k, (c18[0] + 1.2, c18[1] + 0.3), (c18[0], c18[1] + 0.3), (c19[0], c19[1] + 0.3)])
    T("+12V_BOOST", 0.6, [c19, (q1s[0] + 0.8, q1s[1]), q1s])
    c18g, c19g = P("C18", "2"), P("C19", "2")
    T("GND", 0.4, [u4["2"], (c18g[0] + 0.9, u4["2"][1]), c18g])        # 昇圧の GND の戻り (おもて)
    T("GND", 1.0, [c18g, c19g])
    for g in (c18g, c19g):
        bd.gnd_via(g[0], g[1] + 1.45, frm=g, width=0.6)
    bd.gnd_via(c19g[0] - 1.3, c19g[1] + 0.9, frm=c19g, width=0.6)
    for ref in ("C16", "C17"):
        g = P(ref, "2")
        bd.gnd_via(g[0], g[1] + 1.4, frm=g, width=0.6)
    # FB と EN
    r12, r11 = P("R12", "1"), P("R11", "2")
    T("FB_12V", 0.25, [u4["3"], r12])
    T("FB_12V", 0.25, [(r12[0], r11[1]), r11])
    bd.gnd_via(P("R12", "2")[0] - 1.15, P("R12", "2")[1], frm=P("R12", "2"))
    # R11 の上側 (+12V_BOOST) は、GND の戻りの線をうらでくぐって D4 と C18 の間につなぐ
    r11b = P("R11", "1")
    vb1, vb2 = (r11b[0] - 1.05, r11b[1]), (r11b[0] - 1.05, c18[1] + 0.3)
    T("+12V_BOOST", 0.3, [r11b, vb1])
    bd.via("+12V_BOOST", *vb1)
    T("+12V_BOOST", 0.3, [vb1, vb2], layer=B)
    bd.via("+12V_BOOST", *vb2)
    r13 = P("R13", "1")
    T("EN_12V", 0.25, [u4["4"], (u4["4"][0], r13[1] - 0.6), r13])
    bd.gnd_via(P("R13", "2")[0] + 1.15, r13[1], frm=P("R13", "2"))
    # 出力スイッチ -> JP2 -> スロット
    jp2a, jp2b = P("JP2", "1"), P("JP2", "2")
    T("+12V_SW", 0.8, [q1d, jp2a])
    a2, a3, b1, b2, b3 = (P("J3", n) for n in ("A2", "A3", "B1", "B2", "B3"))
    xv = jp2b[0]
    T("+12V", 1.0, [jp2b, (xv, 28.8), (b2[0] + 0.3, 27.1), b2])
    T("+12V", 0.8, [b2, b1])
    T("+12V", 0.8, [b2, b3])
    T("+12V", 0.8, [b1, (5.9, b1[1]), (5.9, a2[1]), a2])
    T("+12V", 0.8, [a2, a3])
    for ref in ("C29", "C30", "R18"):
        p = P(ref, "1")
        T("+12V", 0.5, [p, (xv, p[1])])
        g = P(ref, "2")
        bd.gnd_via(g[0] - (1.4 if ref == "C29" else 1.1), g[1], frm=g)
    p = P("TP3", "1")
    T("+12V", 0.6, [p, (xv, p[1])])
    p = P("R17", "1")
    T("+12V", 0.4, [p, (xv, p[1])])

    # ======== 5V とマイコンの電源 =============================================
    T("GND", 0.4, [P("C7", "2"), (P("U6", "1")[0] + 1.3, P("U6", "1")[1])])
    T("+5V", 0.5, [P("U6", "3"), P("C7", "1")])
    # U7: 9 番 (VDD) と 7 番 (VSS) の真下に C21
    c21p, c21g = P("C21", "1"), P("C21", "2")
    T("+5V", 0.3, [P("U7", "9"), (P("U7", "9")[0], c21p[1] - 0.9), c21p])
    T("GND", 0.3, [P("U7", "7"), (P("U7", "7")[0], c21g[1] - 0.9), c21g])
    T("+5V", 0.4, [c21p, (c21p[0], c21p[1] + 1.0), (P("C22", "1")[0], c21p[1] + 1.0), P("C22", "1")])
    bd.gnd_via(c21g[0] - 1.15, c21g[1], frm=c21g)
    T("SW1_IN", 0.25, [P("R19", "2"), P("SW1", "2")])
    T("LED5_A", 0.25, [P("R20", "2"), P("LED5", "1")])

    # ======== GND のビア (部品の GND のパッドのすぐ横) ========================
    # (参照名, パッド, ビアの位置のずれ dx, dy)
    for ref, num, dx, dy in (
            ("C1", "2", -1.1, 0), ("C3", "2", -1.1, 0), ("R1", "2", 1.15, 0), ("R4", "2", 0, 1.2),
            ("C23", "2", 0, 1.2), ("C24", "2", -1.1, 0), ("C4", "2", -1.3, 0), ("C5", "2", -1.3, 0),
            ("D3", "1", -1.4, 0), ("R24", "2", -1.1, 0), ("C25", "2", -1.1, 0), ("R9", "2", 1.1, 0),
            ("C15", "2", 1.1, 0), ("R26", "2", 1.1, 0), ("C26", "2", 1.1, 0), ("C6", "2", 0, -1.3),
            ("U6", "1", 1.3, 0), ("C22", "2", 1.15, 0),
            ("LED3", "2", -1.3, 0), ("LED4", "2", 0, 1.3), ("LED5", "2", 1.3, 0),
            ("R16", "2", -1.1, 0), ("Q2", "2", 1.25, 0), ("C2", "2", 1.1, 0),
            ("R3", "2", 1.1, 0), ("J4", "7", 1.5, 0), ("TP5", "1", 0, 1.3), ("J5", "2", 0, -1.7),
            ("SW1", "1", 0, -1.5)):
        p = P(ref, num)
        bd.gnd_via(p[0] + dx, p[1] + dy, frm=p)
    # U1・U2 の裏のパッド (GND)
    for u in ("U1", "U2"):
        p = P(u, "11")
        bd.via("GND", p[0], p[1] - 0.6)
        bd.via("GND", p[0], p[1] + 0.6)

    # ここまでの線は固定する (自動配線が動かさないように)
    for t in bd.b.GetTracks():
        t.SetLocked(True)


def keepouts(bd: Board):
    """うらの GND を切らせたくない所 (USB のデータ線の下、降圧と昇圧の下) は、うらの配線を禁止する。"""
    bd.keepout([B], rect(69.0, 10.3, 78.8, 14.8), name="usb-gnd-1")
    bd.keepout([B], rect(80.0, 10.9, 82.9, 15.7), name="usb-gnd-2")
    bd.keepout([B], rect(35.0, 1.0, 56.0, 11.0), name="buck-gnd")
    bd.keepout([B], rect(25.2, 32.4, 38.5, 40.2), name="boost-gnd")


def silk(bd: Board):
    """シルクの文字と印。finish_board.py が、配線のあとで呼ぶ。"""
    t = bd.text
    t("1 PC", 80.2, 7.2, 1.3, 0.2)
    t("DATA+PWR", 77.5, 2.2, 1.0, 0.15)
    t("2 CHARGER", 73.8, 41.6, 1.3, 0.2)
    t("PWR ONLY", 73.8, 43.4, 1.0, 0.15)
    t("PCIe TUNER EXT POWER", 46.0, 2.0, 1.0, 0.15)
    t("rev A 2026-11", 47.0, 15.5, 1.0, 0.15)
    t("<- BRACKET", 9.0, 9.5, 1.0, 0.15)
    t("JP1 3V3", 26.6, 3.3, 1.0, 0.15)
    t("JP2 12V", 12.2, 41.0, 1.0, 0.15)


def main():
    bd = build()
    route(bd)
    keepouts(bd)
    os.makedirs(os.path.join(ROOT, "build"), exist_ok=True)
    out = os.path.join(ROOT, "build", "pre_route.kicad_pcb")
    bd.save(out)
    for ext in ("kicad_pro", "kicad_dru"):
        shutil.copyfile(os.path.join(ROOT, "pcie-tuner-board." + ext), os.path.join(ROOT, "build", "pre_route." + ext))
    for f in ("fp-lib-table", "sym-lib-table"):
        shutil.copyfile(os.path.join(ROOT, f), os.path.join(ROOT, "build", f))
    print("saved", out, "footprints", len(bd.fps))
    return bd


if __name__ == "__main__":
    main()
